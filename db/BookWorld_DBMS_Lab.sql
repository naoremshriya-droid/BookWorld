CREATE TABLE BW_LAB_INSERT_LOG (
    log_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id NUMBER,
    user_id NUMBER,
    book_id NUMBER,
    action_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP
