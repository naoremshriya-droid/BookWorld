-- -- Normalization is demonstrated/documented below; it is not a SQL command.
-- --
-- -- UNNORMALIZED example:
-- -- ORDER_DETAIL(order_id, customer_name, book1, book2, book3)
-- -- Repeating book columns violate 1NF.
-- --
-- -- 1NF: one value per cell and no repeating groups.
-- -- Example: BW_ORDER_ITEMS stores one book per row, with order_id,
-- -- book_id, quantity and unit_price.
-- --
-- -- 2NF: 1NF plus every non-key attribute depends on the whole candidate key.
-- -- BW_BOOK_AUTHORS uses composite PK (book_id, author_id) and has no
-- -- additional non-key attributes, so there is no partial dependency.
-- --
-- -- 3NF: 2NF plus no transitive dependency of non-key attributes on a key.
-- -- BW_BOOKS stores category_id, not category_name; category_name is kept
-- -- in BW_CATEGORIES.
-- --
-- -- BCNF: for every non-trivial functional dependency X -> Y, X is a
-- -- superkey. Review all candidate keys and dependencies for each relation.
-- --
-- -- Example functional dependencies:
-- -- BW_USERS: user_id -> full_name, email, password_hash, created_at
-- -- BW_AUTHORS: author_id -> author_name, bio
-- -- BW_CATEGORIES: category_id -> category_name, description
-- -- BW_BOOKS: book_id -> title, price, stock, category_id
-- -- BW_ORDERS: order_id -> user_id, order_date, order_status, total_amount
-- -- BW_ORDER_ITEMS: order_item_id -> order_id, book_id, quantity, unit_price
-- -- Also (order_id, book_id) -> quantity, unit_price because of the unique
-- -- constraint on (order_id, book_id).
-- --
-- -- Decomposition example:
-- -- ORDER_DETAIL(order_id, customer_name, book_id, book_title, quantity)
-- -- can be decomposed into:
-- -- BW_ORDERS(order_id, user_id, order_date, order_status, total_amount)
-- -- BW_BOOKS(book_id, title, price, stock, category_id)
-- -- BW_ORDER_ITEMS(order_item_id, order_id, book_id, quantity, unit_price)
-- -- Customer details remain in BW_USERS; category details remain in BW_CATEGORIES.

