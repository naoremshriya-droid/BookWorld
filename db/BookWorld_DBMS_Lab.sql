DECLARE
    CURSOR c_books IS
        SELECT title, price
        FROM BW_BOOKS
        ORDER BY title;
    v_title BW_BOOKS.title%TYPE;
    v_price BW_BOOKS.price%TYPE;
BEGIN
    OPEN c_books;
    LOOP
        FETCH c_books INTO v_title, v_price;
        EXIT WHEN c_books%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE(v_title || ' - Rs. ' || v_price);
    END LOOP;
    CLOSE c_books;
END;
/

