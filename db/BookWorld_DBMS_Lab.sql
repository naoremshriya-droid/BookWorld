CREATE TABLE BW_LAB_BOOK_PRICE_AUDIT (
    audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id NUMBER,
    old_price NUMBER(10,2),
    new_price NUMBER(10,2),
    changed_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- INSERT trigger: log a newly inserted review.
CREATE OR REPLACE TRIGGER BW_LAB_REVIEW_INSERT_TRG
AFTER INSERT ON BW_REVIEWS
FOR EACH ROW
BEGIN
    INSERT INTO BW_LAB_INSERT_LOG (review_id, user_id, book_id)
    VALUES (:NEW.review_id, :NEW.user_id, :NEW.book_id);
END;
/

-- UPDATE trigger: preserve old and new prices in audit history.
CREATE OR REPLACE TRIGGER BW_LAB_BOOK_PRICE_UPD_TRG
AFTER UPDATE OF price ON BW_BOOKS
FOR EACH ROW
WHEN (OLD.price <> NEW.price)
BEGIN
    INSERT INTO BW_LAB_BOOK_PRICE_AUDIT (book_id, old_price, new_price)
    VALUES (:NEW.book_id, :OLD.price, :NEW.price);
END;
/

-- DELETE trigger: prevent deleting a book that appears in an order item.
CREATE OR REPLACE TRIGGER BW_LAB_BOOK_DELETE_RESTRICT_TRG
BEFORE DELETE ON BW_BOOKS
FOR EACH ROW
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count
    FROM BW_ORDER_ITEMS
    WHERE book_id = :OLD.book_id;

    IF v_count > 0 THEN
        RAISE_APPLICATION_ERROR(
            -20051,
            'Cannot delete this book because it appears in an order.'
        );
    END IF;
END;
/

