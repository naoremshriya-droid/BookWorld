BEGIN
    FOR t IN (
        SELECT table_name
        FROM user_tables
        WHERE table_name IN (
            'BW_REVIEWS',
            'BW_PAYMENTS',
            'BW_ORDER_ITEMS',
            'BW_ORDERS',
            'BW_BOOK_AUTHORS',
            'BW_BOOKS',
            'BW_CATEGORIES',
            'BW_AUTHORS',
            'BW_USERS'
        )
    ) LOOP
        EXECUTE IMMEDIATE
            'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- 2. USERS
-- Stores registration and login information.


CREATE TABLE BW_USERS (
    user_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name     VARCHAR2(100) NOT NULL,
    email         VARCHAR2(150) NOT NULL,
    password_hash VARCHAR2(255) NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_bw_users PRIMARY KEY (user_id),
    CONSTRAINT uq_bw_users_email UNIQUE (email)
);

-- 3. AUTHORS
-- Stores book author details.


CREATE TABLE BW_AUTHORS (
    author_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    author_name VARCHAR2(100) NOT NULL,
    bio         VARCHAR2(500),
    CONSTRAINT pk_bw_authors PRIMARY KEY (author_id)
);

-- 4. CATEGORIES
-- Stores book categories or genres.


CREATE TABLE BW_CATEGORIES (
    category_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    category_name VARCHAR2(60) NOT NULL,
    description   VARCHAR2(250),
    CONSTRAINT pk_bw_categories PRIMARY KEY (category_id),
    CONSTRAINT uq_bw_category_name UNIQUE (category_name)
);

-- 5. BOOKS
-- Stores catalog details, prices and available stock.


CREATE TABLE BW_BOOKS (
    book_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    title       VARCHAR2(200) NOT NULL,
    price       NUMBER(10,2) NOT NULL,
    stock       NUMBER DEFAULT 0 NOT NULL,
    category_id NUMBER NOT NULL,
    CONSTRAINT pk_bw_books PRIMARY KEY (book_id),
    CONSTRAINT chk_bw_book_price CHECK (price >= 0),
    CONSTRAINT chk_bw_book_stock CHECK (stock >= 0),
    CONSTRAINT fk_bw_book_category
        FOREIGN KEY (category_id)
        REFERENCES BW_CATEGORIES(category_id)
);


-- 6. BOOK_AUTHORS
-- Many-to-many relationship between books and authors.


CREATE TABLE BW_BOOK_AUTHORS (
    book_id   NUMBER NOT NULL,
    author_id NUMBER NOT NULL,
    CONSTRAINT pk_bw_book_authors
        PRIMARY KEY (book_id, author_id),
    CONSTRAINT fk_bw_ba_book
        FOREIGN KEY (book_id)
        REFERENCES BW_BOOKS(book_id),
    CONSTRAINT fk_bw_ba_author
        FOREIGN KEY (author_id)
        REFERENCES BW_AUTHORS(author_id)
);

-- 7. ORDERS
-- Stores customer orders and checkout totals.
-- CART status can be used for a saved shopping cart.


CREATE TABLE BW_ORDERS (
    order_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id      NUMBER NOT NULL,
    order_date   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    order_status VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    total_amount NUMBER(10,2) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_bw_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_bw_order_user
        FOREIGN KEY (user_id)
        REFERENCES BW_USERS(user_id),
    CONSTRAINT chk_bw_order_total
        CHECK (total_amount >= 0),
    CONSTRAINT chk_bw_order_status
        CHECK (order_status IN (
            'CART', 'PENDING', 'CONFIRMED',
            'SHIPPED', 'DELIVERED', 'CANCELLED'
        ))
);


-- 8. ORDER_ITEMS
-- Stores books and quantities within each order.
-- unit_price preserves the purchase-time price.


CREATE TABLE BW_ORDER_ITEMS (
    order_item_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    order_id      NUMBER NOT NULL,
    book_id       NUMBER NOT NULL,
    quantity      NUMBER NOT NULL,
    unit_price    NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_bw_order_items PRIMARY KEY (order_item_id),
    CONSTRAINT fk_bw_item_order
        FOREIGN KEY (order_id)
        REFERENCES BW_ORDERS(order_id),
    CONSTRAINT fk_bw_item_book
        FOREIGN KEY (book_id)
        REFERENCES BW_BOOKS(book_id),
    CONSTRAINT chk_bw_item_qty CHECK (quantity > 0),
    CONSTRAINT chk_bw_item_price CHECK (unit_price >= 0),
    CONSTRAINT uq_bw_order_book UNIQUE (order_id, book_id)
);

-- ============================================================
-- 9. PAYMENTS
-- Stores payment records associated with orders.
-- Never store card numbers or CVV values here.
-- ============================================================

CREATE TABLE BW_PAYMENTS (
    payment_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    order_id        NUMBER NOT NULL,
    payment_method  VARCHAR2(30) NOT NULL,
    payment_status  VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    amount          NUMBER(10,2) NOT NULL,
    paid_at         TIMESTAMP,
    transaction_ref VARCHAR2(100),
    CONSTRAINT pk_bw_payments PRIMARY KEY (payment_id),
    CONSTRAINT fk_bw_payment_order
        FOREIGN KEY (order_id)
        REFERENCES BW_ORDERS(order_id),
    CONSTRAINT chk_bw_payment_amount CHECK (amount >= 0),
    CONSTRAINT chk_bw_payment_method
        CHECK (payment_method IN (
            'UPI', 'CARD', 'NETBANKING', 'COD'
        )),
    CONSTRAINT chk_bw_payment_status
        CHECK (payment_status IN (
            'PENDING', 'SUCCESS', 'FAILED', 'REFUNDED'
        ))
);

-- ============================================================
-- 10. REVIEWS
-- Stores customer ratings and written reviews.
-- Each user can review a particular book once.
-- ============================================================

CREATE TABLE BW_REVIEWS (
    review_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    user_id     NUMBER NOT NULL,
    book_id     NUMBER NOT NULL,
    rating      NUMBER NOT NULL,
    review_text VARCHAR2(1000),
    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_bw_reviews PRIMARY KEY (review_id),
    CONSTRAINT fk_bw_review_user
        FOREIGN KEY (user_id)
        REFERENCES BW_USERS(user_id),
    CONSTRAINT fk_bw_review_book
        FOREIGN KEY (book_id)
        REFERENCES BW_BOOKS(book_id),
    CONSTRAINT chk_bw_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT uq_bw_user_book_review UNIQUE (user_id, book_id)
);

